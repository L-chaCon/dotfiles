#!/usr/bin/env python3
"""Validate every ENTRY.md / PROJECT.md and regenerate INDEX.md at the library root.

Usage: build_index.py
Exits non-zero if any entry is missing required frontmatter.
"""

import os
import sys
from pathlib import Path

LIBRARY = Path(os.environ.get("AI_DOCS_DIR", "~/.ai_docs")).expanduser()
ENTRY_REQUIRED = ["title", "project", "topic", "type", "status", "tags", "created", "updated", "summary"]
PROJECT_REQUIRED = ["name", "slug", "context", "status", "summary"]


def frontmatter(file: Path) -> dict[str, str]:
    """Top-level scalar keys only; nested blocks are skipped."""
    lines = file.read_text().splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    data = {}
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if line[:1].isspace() or line.lstrip().startswith("-") or ":" not in line:
            continue
        key, value = line.split(":", 1)
        data[key.strip()] = value.strip().strip("\"'")
    return data


def cell(value: str) -> str:
    return value.replace("|", "\\|").strip("[]")


def main() -> int:
    errors = []
    projects = []
    entries = []

    for project_file in sorted(LIBRARY.glob("projects/*/PROJECT.md")):
        meta = frontmatter(project_file)
        rel = project_file.relative_to(LIBRARY)
        missing = [k for k in PROJECT_REQUIRED if not meta.get(k)]
        if missing:
            errors.append(f"{rel}: missing {', '.join(missing)}")
        if meta.get("slug") and meta["slug"] != project_file.parent.name:
            errors.append(f"{rel}: slug '{meta['slug']}' does not match directory")
        projects.append((rel, meta))

    for entry_file in sorted(LIBRARY.glob("projects/*/entries/*/ENTRY.md")):
        meta = frontmatter(entry_file)
        rel = entry_file.relative_to(LIBRARY)
        missing = [k for k in ENTRY_REQUIRED if not meta.get(k)]
        if missing:
            errors.append(f"{rel}: missing {', '.join(missing)}")
        if meta.get("project") and meta["project"] != entry_file.parents[2].name:
            errors.append(f"{rel}: project '{meta['project']}' does not match directory")
        if not (entry_file.parents[2] / "PROJECT.md").is_file():
            errors.append(f"{rel}: project has no PROJECT.md")
        if meta.get("topic") and meta["topic"] != entry_file.parent.name:
            errors.append(f"{rel}: topic '{meta['topic']}' does not match directory")
        entries.append((rel, meta))

    entries.sort(key=lambda e: e[1].get("updated", ""), reverse=True)

    out = [
        "# Index",
        "",
        "<!-- Generated by ~/.pi/agent/skills/archive-docs/scripts/build_index.py. Do not edit by hand. -->",
        "",
        f"## Projects ({len(projects)})",
        "",
        "| project | context | status | summary |",
        "|---|---|---|---|",
    ]
    for rel, m in projects:
        out.append(f"| [{m.get('slug', '?')}]({rel}) | " + " | ".join(cell(m.get(k, "")) for k in ("context", "status", "summary")) + " |")

    out += [
        "",
        f"## Entries ({len(entries)}, newest first)",
        "",
        "| updated | project | entry | type | status | tags | summary |",
        "|---|---|---|---|---|---|---|",
    ]
    for rel, m in entries:
        cells = [cell(m.get(k, "")) for k in ("updated", "project")]
        cells.append(f"[{m.get('topic', '?')}]({rel})")
        cells += [cell(m.get(k, "")) for k in ("type", "status", "tags", "summary")]
        out.append("| " + " | ".join(cells) + " |")

    (LIBRARY / "INDEX.md").write_text("\n".join(out) + "\n")
    print(f"INDEX.md: {len(projects)} projects, {len(entries)} entries")
    for error in errors:
        print(f"ERROR {error}", file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
